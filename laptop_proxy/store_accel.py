# -*- coding: utf-8 -*-
"""beta1.0.57: Store accelerator (Steam / Epic) — Mihomo as a separate helper
process.

Design constraints (deliberate):
- **No nodes are bundled, distributed or fetched by LinkHelm.** The user
  imports their OWN subscription URL or config file; it is stored locally
  only and never shipped with the app. (Same policy as FlClash / Clash
  Verge: the kernel is generic, the user brings the config.)
- **Mihomo runs as an UNMODIFIED external binary in a separate process**
  (GPL-3.0). It is never linked or compiled into LinkHelm, so the GPL does
  not extend to LinkHelm (MIT) — see THIRD_PARTY_NOTICES.md for the source
  link required by the license.
- **No new network adapter.** Mihomo only listens on 127.0.0.1:<port>
  (mixed HTTP+SOCKS). Optional WinINET system-proxy toggle. All outbound
  traffic uses whatever route the OS already has — the LinkHelm tunnel when
  connected, the physical NIC otherwise.
- Rule set covers the store/community domains of Steam and Epic only;
  everything else stays DIRECT, so daily traffic and games are untouched.
"""

import atexit
import hashlib
import os
import shutil
import subprocess
import sys
import threading

MIHOMO_VERSION = "v1.19.33"
MIHOMO_SHA256 = "1cde41cfffd3de0aedad63c0a8515e1ce5eea507e8133aed0f637d316c93800a"
MIXED_PORT = 7890

# Store/community/CDN-host domains ONLY. Game traffic and everything else
# stays DIRECT (no GEOIP database download needed — plain domain rules).
STEAM_DOMAINS = (
    "steampowered.com",      # store / api / help
    "steamcommunity.com",    # community / market
    "steamstatic.com",       # store static assets
    "steam-chat.com",        # chat
    "steamserver.net",       # store CDN edge selection
)
EPIC_DOMAINS = (
    "epicgames.com",         # store / launcher
    "epicgames.dev",         # storefront assets
    "unrealengine.com",      # launcher services
)


def find_mihomo_exe():
    """Locate the bundled mihomo.exe (frozen: _MEIPASS/mihomo, dev: ./mihomo).
    Returns (path, None) or (None, reason)."""
    candidates = []
    base = getattr(sys, "_MEIPASS", None)
    if base:
        candidates.append(os.path.join(base, "mihomo", "mihomo.exe"))
    candidates.append(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                   "mihomo", "mihomo.exe"))
    for path in candidates:
        if os.path.isfile(path):
            digest = _sha256_file(path)
            if digest != MIHOMO_SHA256:
                return None, ("mihomo.exe hash mismatch (%s...); refused to run a "
                              "replaced binary" % digest[:12])
            return path, None
    return None, "mihomo.exe not found next to the app (mihomo/ folder missing)"


def _sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as fin:
        for chunk in iter(lambda: fin.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def generate_config_text(sub_url):
    """Build a minimal rule-mode config for the store accelerator.

    `sub_url` must be an http(s) subscription handled by mihomo's
    proxy-provider (health-checked). Store domains -> STORE group,
    everything else -> DIRECT.
    """
    domain_rules = "".join(
        "  - DOMAIN-SUFFIX,%s,STORE\n" % d for d in STEAM_DOMAINS + EPIC_DOMAINS
    )
    # NOTE: yaml written by hand (no PyYAML dependency); values are fixed
    # constants and the url is yaml-quoted, so no escaping surprises.
    return (
        "# Generated by LinkHelm store accelerator (user-supplied subscription).\n"
        "# No nodes are bundled with LinkHelm; this file references YOUR provider.\n"
        "mixed-port: %d\n"
        "allow-lan: false\n"
        "bind-address: 127.0.0.1\n"
        "mode: rule\n"
        "log-level: warning\n"
        "unified-delay: true\n"
        "profile:\n"
        "  store-selected: true\n"
        "dns:\n"
        "  enable: true\n"
        "  nameserver:\n"
        "    - 223.5.5.5\n"
        "    - 119.29.29.29\n"
        "proxy-providers:\n"
        "  sub:\n"
        "    type: http\n"
        "    url: \"%s\"\n"
        "    interval: 86400\n"
        "    path: ./providers/sub.yaml\n"
        "    health-check:\n"
        "      enable: true\n"
        "      url: https://www.gstatic.com/generate_204\n"
        "      interval: 300\n"
        "proxy-groups:\n"
        "  - name: STORE\n"
        "    type: select\n"
        "    use:\n"
        "      - sub\n"
        "rules:\n"
        "%s"
        "  - MATCH,DIRECT\n" % (MIXED_PORT, sub_url.strip(), domain_rules)
    )


# ---------------------------------------------------------------------------
# WinINET system proxy (HKCU\...\Internet Settings) — the SAME store the
# Windows "Proxy" settings page edits. Steam's embedded browser and the Epic
# launcher both honour it. Prior state is captured once and restored on
# stop/shutdown, so a crash cannot leave a stale proxy behind silently.
# ---------------------------------------------------------------------------

_PROXY_REG_PATH = (r"Software\Microsoft\Windows\CurrentVersion"
                   r"\Internet Settings")
_INTERNET_OPTION_SETTINGS_CHANGED = 39
_INTERNET_OPTION_REFRESH = 37


def _refresh_wininet():
    try:
        import ctypes
        wininet = ctypes.WinDLL("wininet")
        wininet.InternetSetOptionW(None, _INTERNET_OPTION_SETTINGS_CHANGED,
                                   None, 0)
        wininet.InternetSetOptionW(None, _INTERNET_OPTION_REFRESH, None, 0)
    except Exception:
        pass  # best effort; Explorer usually picks the change up anyway


def read_system_proxy():
    """Return (enabled, server) currently set in WinINET."""
    try:
        import winreg
        with winreg.OpenKey(winreg.HKEY_CURRENT_USER, _PROXY_REG_PATH) as key:
            enabled, _ = winreg.QueryValueEx(key, "ProxyEnable")
            try:
                server, _ = winreg.QueryValueEx(key, "ProxyServer")
            except OSError:
                server = ""
        return bool(enabled), server or ""
    except Exception:
        return False, ""


def write_system_proxy(enabled, server):
    """Set/clear the WinINET proxy and notify the system."""
    import winreg
    with winreg.CreateKey(winreg.HKEY_CURRENT_USER, _PROXY_REG_PATH) as key:
        winreg.SetValueEx(key, "ProxyEnable", 0, winreg.REG_DWORD,
                          1 if enabled else 0)
        if enabled and server:
            winreg.SetValueEx(key, "ProxyServer", 0, winreg.REG_SZ, server)
            winreg.SetValueEx(key, "ProxyOverride", 0, winreg.REG_SZ,
                              "localhost;127.*;10.*;172.16.*;192.168.*;<local>")
    _refresh_wininet()


class StoreAccel(object):
    """Lifecycle for the mihomo helper process. All methods are safe to call
    from any thread; UI reads the returned state strings."""

    def __init__(self, config_dir, log_fn):
        self.log = log_fn
        self.workdir = os.path.join(config_dir, "mihomo")
        self.proc = None
        self._log_tail = []          # last stderr lines for error reporting
        self._lock = threading.RLock()
        self._saved_proxy = None     # (enabled, server) captured on enable
        self._sysproxy_on = False
        atexit.register(self.shutdown)

    # -- settings (accel.json next to settings.json; local-only) -----------

    def _pref_path(self):
        return os.path.join(os.path.dirname(self.workdir), "accel.json")

    def load_pref(self):
        import json
        try:
            with open(self._pref_path(), encoding="utf-8") as fin:
                return json.load(fin)
        except Exception:
            return {}

    def save_pref(self, **kwargs):
        import json
        data = self.load_pref()
        data.update(kwargs)
        try:
            os.makedirs(os.path.dirname(self._pref_path()), exist_ok=True)
            with open(self._pref_path(), "w", encoding="utf-8") as fout:
                json.dump(data, fout, ensure_ascii=False, indent=2)
        except Exception:
            pass

    # -- state --------------------------------------------------------------

    def is_running(self):
        return self.proc is not None and self.proc.poll() is None

    def status_text(self):
        with self._lock:
            if self.is_running():
                return "running  127.0.0.1:%d" % MIXED_PORT
            if self.proc is not None:
                tail = " ".join(self._log_tail[-3:])[-200:]
                return "stopped: %s" % (tail or "exit code %s" % self.proc.returncode)
            return ""

    # -- start / stop ---------------------------------------------------------

    def start(self, sub_url, use_sysproxy):
        with self._lock:
            if self.is_running():
                return True, "already running"
            exe, err = find_mihomo_exe()
            if exe is None:
                return False, err
            sub_url = (sub_url or "").strip()
            if not sub_url:
                return False, ("import a subscription URL or config.yaml first "
                               "(no nodes are bundled with LinkHelm)")
            os.makedirs(self.workdir, exist_ok=True)
            os.makedirs(os.path.join(self.workdir, "providers"), exist_ok=True)
            if sub_url.lower().endswith((".yaml", ".yml")) and \
                    os.path.isfile(sub_url):
                cfg_path = os.path.join(self.workdir, "config.yaml")
                shutil.copyfile(sub_url, cfg_path)
                self.log("[accel] using user config file: %s" % sub_url)
            elif sub_url.lower().startswith(("http://", "https://")):
                cfg_path = os.path.join(self.workdir, "config.yaml")
                with open(cfg_path, "w", encoding="utf-8") as fout:
                    fout.write(generate_config_text(sub_url))
            else:
                return False, "not a subscription URL or an existing .yaml file"
            self._log_tail = []
            try:
                self.proc = subprocess.Popen(
                    [exe, "-d", self.workdir, "-f", cfg_path],
                    stdout=subprocess.DEVNULL, stderr=subprocess.PIPE,
                    creationflags=(getattr(subprocess, "CREATE_NO_WINDOW", 0)
                                   if os.name == "nt" else 0),
                )
            except Exception as exc:
                self.proc = None
                return False, "failed to launch mihomo: %s" % exc
            threading.Thread(target=self._pump_stderr, daemon=True).start()
            if use_sysproxy:
                self.enable_system_proxy()
            self.save_pref(subUrl=sub_url, sysProxy=bool(use_sysproxy))
            return True, self.status_text()

    def stop(self):
        with self._lock:
            self.disable_system_proxy()
            proc, self.proc = self.proc, None
            if proc is not None and proc.poll() is None:
                try:
                    proc.terminate()
                    try:
                        proc.wait(timeout=3)
                    except Exception:
                        proc.kill()
                except Exception:
                    pass
                self.log("[accel] store accelerator stopped")

    def shutdown(self):
        self.stop()

    # -- internals ------------------------------------------------------------

    def _pump_stderr(self):
        proc = self.proc
        try:
            for raw in iter(proc.stderr.readline, b""):
                line = raw.decode("utf-8", "replace").strip()
                if line:
                    with self._lock:
                        self._log_tail.append(line)
                        del self._log_tail[:-20]
        except Exception:
            pass

    def enable_system_proxy(self):
        if self._sysproxy_on:
            return
        prev = read_system_proxy()
        self._saved_proxy = prev
        write_system_proxy(True, "127.0.0.1:%d" % MIXED_PORT)
        self._sysproxy_on = True
        self.log("[accel] system proxy -> 127.0.0.1:%d (was: %s)"
                 % (MIXED_PORT, prev[1] or "off"))

    def disable_system_proxy(self):
        if not self._sysproxy_on:
            return
        self._sysproxy_on = False
        saved = self._saved_proxy or (False, "")
        self._saved_proxy = None
        try:
            write_system_proxy(saved[0], saved[1])
            self.log("[accel] system proxy restored (%s)"
                     % (saved[1] or "off"))
        except Exception:
            pass
